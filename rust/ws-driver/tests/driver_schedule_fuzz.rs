/// The main campaign: drawn command/byte/EOF/write-progress/shutdown
/// schedules against a real `ConnectionDriver`, each run twice for the
/// determinism oracle.
#[test]
fn owner_driver_schedule_soup_no_panic_deterministic() {
    let mut rng = SplitMix64::new(0xd21e_0001);
    let mut reached = Reached::default();
    for case in 0..4_000u32 {
        let role = draw_role(&mut rng);
        let (auto, echo) = draw_policies(&mut rng);
        let schedule = draw_schedule(&mut rng, role);
        let label = format!("owner_driver schedule case {case}");
        let seed = 0x9403_0000 + u64::from(case);
        let first = execute_checked(&label, &schedule, role, auto, echo, seed);
        let second = execute_checked(&label, &schedule, role, auto, echo, seed);
        assert_eq!(
            first, second,
            "{label}: determinism (identical full owner trace)"
        );
        assert!(
            first.terminals <= 1,
            "{label}: the terminal must be delivered at most once"
        );
        reached.wire += usize::from(!first.wire.is_empty());
        reached.terminals += first.terminals;
        reached.failures += usize::from(first.failures > 0);
        reached.events += usize::from(!first.events.is_empty());
        reached.dropped += usize::from(!first.dropped.is_empty());
    }
    // Coverage floors. A campaign whose every case dies on its first inbound
    // frame runs 4,000 times and exercises nothing; these floors are what
    // stops that degeneration from passing silently.
    //
    // The campaign is fully deterministic (fixed seed, fixed generator), so
    // these are exact reproducible observations, not estimates. Measured on
    // the landed generator: wire 1352, terminals 151, failures 3363,
    // events 3347, dropped 517. The floors sit below each with margin. A
    // deliberate generator change that legitimately moves them is expected
    // to move these numbers WITH a recorded reason, not to delete them.
    reached.assert_floors("owner_driver schedule soup");
}

/// How much of the driver's behavior a campaign actually reached.
#[derive(Debug, Default)]
struct Reached {
    wire: usize,
    terminals: usize,
    failures: usize,
    events: usize,
    dropped: usize,
}

impl Reached {
    fn assert_floors(&self, campaign: &str) {
        assert!(
            self.wire >= 1_000,
            "{campaign}: only {} cases put a byte on the wire",
            self.wire
        );
        assert!(
            self.terminals >= 100,
            "{campaign}: only {} cases reached the terminal",
            self.terminals
        );
        assert!(
            self.failures >= 2_000,
            "{campaign}: only {} cases surfaced a fatal",
            self.failures
        );
        assert!(
            self.events >= 2_500,
            "{campaign}: only {} cases drained a semantic event",
            self.events
        );
        assert!(
            self.dropped >= 350,
            "{campaign}: only {} cases surfaced a dropped-write report",
            self.dropped
        );
    }
}

/// Schedules that ALWAYS end the transport, so the shutdown/EOF accounting
/// oracles are reached on every case rather than occasionally. The
/// exhaustive exploration reaches shutdown only under
/// `AutoResponsePolicy::Disabled`; this family draws both policies.
#[test]
fn owner_driver_transport_termination_accounting() {
    let mut rng = SplitMix64::new(0xd21e_0002);
    let mut with_reports = 0usize;
    for case in 0..3_000u32 {
        let role = draw_role(&mut rng);
        let (auto, echo) = draw_policies(&mut rng);
        let mut schedule = draw_schedule(&mut rng, role);
        // Guarantee committed but undrained wire output before the end.
        schedule.push((
            Step::Enqueue {
                producer: 0,
                command: draw_command(&mut rng),
            },
            ProgressKind::None,
        ));
        schedule.push((Step::Wake, ProgressKind::None));
        if rng.chance(2) {
            schedule.push((Step::WriteProgress(0), ProgressKind::One));
        }
        if rng.chance(2) {
            schedule.push((Step::TransportEof, ProgressKind::None));
        }
        schedule.push((Step::Shutdown, ProgressKind::None));
        let label = format!("owner_driver termination case {case}");
        let seed = 0x9404_0000 + u64::from(case);
        let trace = execute_checked(&label, &schedule, role, auto, echo, seed);
        let replay = execute_checked(&label, &schedule, role, auto, echo, seed);
        assert_eq!(trace, replay, "{label}: determinism");
        if !trace.dropped.is_empty() {
            with_reports += 1;
        }
    }
    assert!(
        with_reports >= 100,
        "a shutdown-accounting campaign that never reaches a dropped-write report \
         proves nothing; reached {with_reports}"
    );
}

/// Backpressure at the bounded producer seam: a command queue of capacity 8
/// with schedules that enqueue far more than that. Every refusal must be
/// the typed bounded refusal, and no accepted command may be lost.
#[test]
fn owner_driver_producer_backpressure_is_typed() {
    let mut rng = SplitMix64::new(0xd21e_0003);
    let mut refusals = 0usize;
    for case in 0..2_000u32 {
        let role = draw_role(&mut rng);
        let (auto, echo) = draw_policies(&mut rng);
        let burst = 8 + rng.below(16) as usize;
        let mut schedule: Vec<(Step, ProgressKind)> = (0..burst)
            .map(|index| {
                (
                    Step::Enqueue {
                        producer: (index & 1) as u8,
                        command: draw_command(&mut rng),
                    },
                    ProgressKind::None,
                )
            })
            .collect();
        for _ in 0..rng.below(6) {
            schedule.push((Step::Wake, ProgressKind::None));
            schedule.push((Step::WriteProgress(0), ProgressKind::Whole));
        }
        let label = format!("owner_driver backpressure case {case}");
        let seed = 0x9405_0000 + u64::from(case);
        let trace = execute_checked(&label, &schedule, role, auto, echo, seed);
        let replay = execute_checked(&label, &schedule, role, auto, echo, seed);
        assert_eq!(trace, replay, "{label}: determinism");
        refusals += trace.refused_enqueues;
        // Every command that was ACCEPTED by the bounded channel must reach
        // a disposition once the owner drains, and none may be invented.
        let accepted = burst - trace.refused_enqueues;
        assert!(
            trace.dispositions.len() <= accepted,
            "{label}: the owner disposed {} commands but only {accepted} were accepted",
            trace.dispositions.len()
        );
        if !trace.halted {
            assert_eq!(
                trace.dispositions.len(),
                accepted,
                "{label}: a quiescent owner must dispose every accepted command"
            );
        }
    }
    assert!(
        refusals >= 100,
        "a backpressure campaign that never fills the bounded channel proves nothing; \
         reached {refusals} refusals"
    );
}

/// The strong form of the invalid-write-progress property, checked where it
/// is actually true: on a QUIESCENT owner (nothing queued, one write
/// offered), a refused progress must move literally nothing -- not the
/// lifecycle state, not one protocol counter, not one byte of the offered
/// suffix.
///
/// This is the deterministic companion to the campaign's weaker per-case
/// check. Keeping the two apart is the point: a poll is an owner turn, so
/// the campaign cannot demand total inertness without becoming an oracle
/// that fails on correct behavior.
#[test]
fn owner_driver_invalid_write_progress_on_a_quiescent_owner_moves_nothing() {
    let (sender, mut driver) = connection_driver_in_state_with_policies(
        config(),
        Role::Server,
        InitialState::Open,
        AutoResponsePolicy::Disabled,
        CloseEchoPolicy::CoreDraftEcho,
    );
    sender
        .try_send(LocalCommand::SendText {
            text: "quiescent".to_owned(),
        })
        .expect("bounded enqueue within capacity");

    // Poll until the write is offered, then keep polling until the owner has
    // nothing left but that offer.
    let mut offered = None;
    for _ in 0..DRAIN_WORK_BOUND {
        let result = driver.poll(DriverInput::Wake);
        match result.output {
            DriverOutput::Write(suffix) => {
                offered = Some(suffix.to_vec());
                break;
            }
            DriverOutput::Idle => panic!("the owner went idle without offering the write"),
            _ => {}
        }
    }
    let offered = offered.expect("the committed text frame must be offered");
    assert!(!offered.is_empty());

    // Take one byte, so the refusal is measured against a partly drained
    // front write rather than a fresh one.
    assert_eq!(
        driver.poll(DriverInput::WriteProgress { bytes: 1 }).input,
        InputDisposition::Consumed { bytes: 0 }
    );
    let remaining = offered.len() - 1;

    let state_before = driver.state();
    let counts_before = driver.counts();
    for overrun in [remaining + 1, remaining + 7, usize::MAX] {
        let result = driver.poll(DriverInput::WriteProgress { bytes: overrun });
        assert_eq!(
            result.input,
            InputDisposition::Rejected(DriverInputError::InvalidWriteProgress {
                attempted: overrun,
                remaining,
            }),
            "an overrun of {overrun} against {remaining} offered bytes must be refused"
        );
        assert_eq!(
            driver.state(),
            state_before,
            "a refused write progress moved the lifecycle state of a quiescent owner"
        );
        assert_eq!(
            driver.counts(),
            counts_before,
            "a refused write progress moved a protocol counter of a quiescent owner"
        );
    }

    // The offer must still be exactly the undrained tail: a refusal may not
    // consume, re-offer, or discard any of it.
    match driver.poll(DriverInput::Wake).output {
        DriverOutput::Write(suffix) => assert_eq!(
            suffix,
            &offered[1..],
            "the refusals disturbed the undrained tail of the offered write"
        ),
        other => panic!("the undrained write must still be offered, got {other:?}"),
    }
}
