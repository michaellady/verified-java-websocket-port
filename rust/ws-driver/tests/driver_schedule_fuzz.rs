// ---------------------------------------------------------------------------
// Deterministic PRNG (SplitMix64) — fixed committed seeds only.
// ---------------------------------------------------------------------------

#[derive(Clone)]
struct SplitMix64 {
    state: u64,
}

impl SplitMix64 {
    fn new(seed: u64) -> SplitMix64 {
        SplitMix64 { state: seed }
    }

    fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: u64) -> u64 {
        assert!(n > 0);
        self.next_u64() % n
    }

    fn byte(&mut self) -> u8 {
        (self.next_u64() & 0xff) as u8
    }

    fn chance(&mut self, one_in: u64) -> bool {
        self.below(one_in) == 0
    }

    fn bytes(&mut self, len: usize) -> Vec<u8> {
        (0..len).map(|_| self.byte()).collect()
    }
}

/// Work bound for the quiescence drain. Exceeding it means a bounded
/// schedule produced unbounded owner output, which is the defect this
/// bound exists to catch. It is NOT the campaign's liveness guard: that is
/// the wall-clock deadline recorded in `assurance/fuzz/manifest.json`.
const DRAIN_WORK_BOUND: usize = 512;

// ---------------------------------------------------------------------------
// Independent frame construction (never calls the shipped encoder).
// ---------------------------------------------------------------------------

fn xor_mask(payload: &mut [u8], key: [u8; 4]) {
    for (index, byte) in payload.iter_mut().enumerate() {
        *byte ^= key[index % 4];
    }
}

fn raw_frame(
    fin: bool,
    rsv: u8,
    opcode: u8,
    payload: &[u8],
    mask: Option<[u8; 4]>,
    force_escape: Option<u8>,
) -> Vec<u8> {
    let mut out = Vec::with_capacity(payload.len() + 14);
    let mut first = opcode & 0x0f;
    if fin {
        first |= 0x80;
    }
    first |= (rsv & 0x07) << 4;
    out.push(first);
    let mask_bit = if mask.is_some() { 0x80u8 } else { 0 };
    let len = payload.len() as u64;
    let escape = match force_escape {
        Some(marker) => marker,
        None if len <= 125 => 0,
        None if len <= 0xffff => 126,
        None => 127,
    };
    match escape {
        126 => {
            out.push(mask_bit | 126);
            out.extend_from_slice(&(len as u16).to_be_bytes());
        }
        127 => {
            out.push(mask_bit | 127);
            out.extend_from_slice(&len.to_be_bytes());
        }
        _ => out.push(mask_bit | (len as u8)),
    }
    if let Some(key) = mask {
        out.extend_from_slice(&key);
        let start = out.len();
        out.extend_from_slice(payload);
        xor_mask(&mut out[start..], key);
    } else {
        out.extend_from_slice(payload);
    }
    out
}

fn draw_close_payload(rng: &mut SplitMix64, hostile: bool) -> Vec<u8> {
    if !hostile {
        let mut payload = 1000u16.to_be_bytes().to_vec();
        payload.extend((0..rng.below(12)).map(|_| (rng.byte() & 0x3f) + 0x20));
        return payload;
    }
    match rng.below(10) {
        0 => Vec::new(),
        1 => vec![rng.byte()],
        _ => {
            const CODES: [u16; 12] = [
                999, 1000, 1001, 1002, 1005, 1006, 1007, 1011, 1015, 2999, 4999, 5000,
            ];
            let code = if rng.chance(4) {
                (rng.next_u64() & 0xffff) as u16
            } else {
                CODES[rng.below(CODES.len() as u64) as usize]
            };
            let mut payload = code.to_be_bytes().to_vec();
            let reason_len = rng.below(20) as usize;
            payload.extend((0..reason_len).map(|_| rng.byte()));
            payload
        }
    }
}

/// One structured inbound frame.
///
/// ## The hostile/well-formed split, and why it exists
///
/// `role` is the LOCAL endpoint, so it decides the masking a peer frame must
/// carry: a server reads client frames, which must be masked, and a client
/// reads server frames, which must not be.
///
/// A generator that draws every field uniformly produces a frame that is
/// PROTOCOL-FATAL most of the time -- unmasked to a server, invalid UTF-8 in
/// a text frame, a reserved opcode, a non-FIN control frame, a continuation
/// with no open fragment. The modeled adapter halts at its first surfaced
/// fatal, exactly like the shipped ws-testee io_loop, so a uniform generator
/// kills its own runs before they reach the driver behavior this campaign
/// exists to exercise. Measured on the uniform version of this generator:
/// 3,470 of 4,000 cases surfaced a fatal and only 134 reached a terminal.
///
/// So three frames in four are drawn WELL-FORMED (role-correct masking, FIN
/// set, a real opcode, valid UTF-8 text, a valid close payload) and the
/// fourth is drawn hostile across every one of those axes. The coverage
/// floors asserted at the end of the campaign are what keep this split
/// honest.
fn draw_frame(rng: &mut SplitMix64, role: Role) -> Vec<u8> {
    let hostile = rng.chance(4);
    let opcode: u8 = if hostile {
        match rng.below(20) {
            0..=1 => 0x0,
            2..=5 => 0x1,
            6..=8 => 0x2,
            9..=12 => 0x8,
            13..=16 => 0x9,
            17..=18 => 0xa,
            _ => rng.byte() & 0x0f,
        }
    } else {
        const WELL_FORMED: [u8; 5] = [0x1, 0x2, 0x9, 0xa, 0x8];
        WELL_FORMED[rng.below(WELL_FORMED.len() as u64) as usize]
    };
    let control = opcode >= 0x8;
    let fin = if hostile { !rng.chance(3) } else { true };
    let rsv = if hostile && rng.chance(3) {
        1 << rng.below(3)
    } else {
        0
    };
    let len = if control {
        rng.below(126) as usize
    } else {
        rng.below(160) as usize
    };
    let payload = match opcode {
        0x8 => draw_close_payload(rng, hostile),
        // A text frame carrying random bytes is almost surely invalid UTF-8,
        // which is fatal. Well-formed text is printable ASCII.
        0x1 if !hostile => (0..len).map(|_| (rng.byte() & 0x3f) + 0x20).collect(),
        _ => rng.bytes(len),
    };
    let peer_masks = role == Role::Server;
    let masked = if hostile && rng.chance(3) {
        !peer_masks
    } else {
        peer_masks
    };
    let mask = if masked {
        Some([rng.byte(), rng.byte(), rng.byte(), rng.byte()])
    } else {
        None
    };
    let force_escape = if payload.len() <= 125 && hostile && rng.chance(8) {
        Some(if rng.chance(2) { 126 } else { 127 })
    } else {
        None
    };
    raw_frame(fin, rsv, opcode, &payload, mask, force_escape)
}

fn draw_command(rng: &mut SplitMix64) -> LocalCommand {
    match rng.below(6) {
        0 => LocalCommand::SendText {
            text: String::from_utf8(
                (0..rng.below(60))
                    .map(|_| (rng.byte() & 0x3f) + 0x20)
                    .collect::<Vec<u8>>(),
            )
            .expect("printable ascii"),
        },
        1 => {
            let len = rng.below(120) as usize;
            LocalCommand::SendBinary {
                data: rng.bytes(len),
            }
        }
        2 => {
            let len = rng.below(126) as usize;
            LocalCommand::SendPing {
                data: rng.bytes(len),
            }
        }
        3 => {
            let len = rng.below(126) as usize;
            LocalCommand::SendPong {
                data: rng.bytes(len),
            }
        }
        4 => {
            const CODES: [u16; 8] = [1000, 1001, 1002, 1005, 1007, 1015, 3000, 4999];
            LocalCommand::SendClose {
                code: if rng.chance(3) {
                    (rng.next_u64() & 0xffff) as u16
                } else {
                    CODES[rng.below(CODES.len() as u64) as usize]
                },
                reason: String::from_utf8(
                    (0..rng.below(20))
                        .map(|_| (rng.byte() & 0x3f) + 0x20)
                        .collect::<Vec<u8>>(),
                )
                .expect("printable ascii"),
            }
        }
        _ => LocalCommand::SendFragment {
            opcode: if rng.chance(2) {
                DataOpcode::Text
            } else {
                DataOpcode::Binary
            },
            data: (0..rng.below(40)).map(|_| rng.byte()).collect(),
            fin: rng.chance(2),
        },
    }
}

