/// One schedule step. Unlike the eleven fixed verbs of the exhaustive
/// exploration, every payload here is DRAWN.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Step {
    /// Producer A or B enqueues a drawn command through the shared bounded
    /// `CommandSender`.
    Enqueue {
        producer: u8,
        command: LocalCommand,
    },
    /// Drawn inbound transport bytes.
    Inbound(Vec<u8>),
    /// The transport accepted this many bytes of the offered suffix. Drawn
    /// values include zero, one, a partial, the whole suffix, and values
    /// PAST the suffix, which must be refused.
    WriteProgress(usize),
    TransportEof,
    Shutdown,
    Wake,
}

/// How a `WriteProgress` value is chosen relative to the offered suffix.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ProgressKind {
    None,
    One,
    Partial,
    Whole,
    /// Deliberately past the end: this must be refused, not absorbed.
    Overrun,
}

fn draw_progress_kind(rng: &mut SplitMix64) -> ProgressKind {
    match rng.below(10) {
        0 => ProgressKind::None,
        1..=2 => ProgressKind::One,
        3..=4 => ProgressKind::Partial,
        5..=7 => ProgressKind::Whole,
        _ => ProgressKind::Overrun,
    }
}

/// Draw one bounded schedule. `WriteProgress` carries a placeholder that the
/// run resolves against the suffix actually offered at that moment; the
/// KIND is what the schedule fixes, which keeps the schedule replayable.
fn draw_schedule(rng: &mut SplitMix64, role: Role) -> Vec<(Step, ProgressKind)> {
    let length = 1 + rng.below(24) as usize;
    (0..length)
        .map(|_| {
            let kind = draw_progress_kind(rng);
            let step = match rng.below(16) {
                0..=4 => Step::Enqueue {
                    producer: rng.byte() & 1,
                    command: draw_command(rng),
                },
                5..=8 => {
                    if rng.chance(6) {
                        let len = rng.below(40) as usize;
                        Step::Inbound(rng.bytes(len))
                    } else {
                        Step::Inbound(draw_frame(rng, role))
                    }
                }
                9..=11 => Step::WriteProgress(0),
                12 => Step::TransportEof,
                13 => Step::Shutdown,
                _ => Step::Wake,
            };
            (step, kind)
        })
        .collect()
}

