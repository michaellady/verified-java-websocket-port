//! US-021 AC2 generative fuzz target for OWNER-DRIVER COMMAND/BYTE
//! SCHEDULES, at the ws-driver seam AC2 actually names.
//!
//! ## Why this file exists
//!
//! `assurance/fuzz/manifest.json` recorded this family `ABSENT`, and the
//! census was right on both counts:
//!
//! - `tests/schedule_exploration.rs` EXHAUSTIVELY ENUMERATES every
//!   interleaving of five fixed actor programs within a context-switch
//!   bound. That is systematic, deterministic and valuable, and it is not
//!   generative fuzzing: it draws nothing. Its alphabet is eleven fixed
//!   verbs and its inbound bytes are two fixed frames.
//! - `adversarial_fuzz.rs::family_command_interleave_no_panic_deterministic`
//!   DOES interleave generated commands with generated bytes, but against
//!   `ConnectionCore` — no `ConnectionDriver`, no owner poll loop, no
//!   transport write path. A different seam.
//!
//! This file draws schedules over a real [`ConnectionDriver`], drives the
//! owner poll loop, and models a transport that accepts write suffixes
//! incrementally. Zero new dependencies: the hand-rolled SplitMix64 from
//! fixed committed seeds is the engine, as in `adversarial_fuzz.rs`.
//!
//! ## What is generated that the enumeration does not draw
//!
//! - inbound BYTES: raw frames built independently of the shipped encoder
//!   (arbitrary FIN/RSV/opcode, both maskings, noncanonical length escapes,
//!   hostile close payloads, invalid UTF-8), plus byte soup and truncations;
//! - commands: all six `LocalCommand` kinds with drawn payloads, from two
//!   producers sharing the bounded `CommandSender`;
//! - write progress: zero, one, a drawn partial, the whole suffix, and
//!   DELIBERATELY OVER the suffix (which must be refused, not absorbed);
//! - both `AutoResponsePolicy` values and both `CloseEchoPolicy` values.
//!   The exploration suite runs `AutoResponsePolicy::Disabled` only and
//!   discloses that it therefore cannot reach any interaction between the
//!   automatic reply and shutdown; this campaign draws the default policy
//!   too.
//!
//! ## Oracles (checked on every case)
//!
//! - **No panic** — every run is under `catch_unwind`, failing the case
//!   with its seed label.
//! - **Determinism** — the same drawn schedule replays to a byte-identical
//!   trace.
//! - **Producer purity (single owner)** — a `CommandSender::try_send` must
//!   not move `driver.state()` or `driver.counts()`. Only the owner's poll
//!   may move a protocol observable.
//! - **Write-suffix continuity** — after the transport accepts `k` bytes of
//!   an offered suffix, the next offer must be exactly that suffix minus its
//!   first `k` bytes (or a different write once the front is fully drained).
//!   The driver may neither re-offer accepted bytes nor drop unaccepted
//!   ones.
//! - **Invalid write progress is refused and inert** — progress past the
//!   offered suffix must come back `Rejected(InvalidWriteProgress)` with the
//!   real `attempted`/`remaining`, and must move no observable at all.
//! - **Exactly-once terminal** — at most one `DriverOutput::Terminal` per
//!   run.
//! - **Shutdown accounting** — at most one `WritesDropped` report; it must
//!   precede any `Terminal`; `frames == 0` exactly when `bytes == 0`; and
//!   when the boundary was holding a partly drained front write, the report
//!   must account for at least its undrained suffix and must set
//!   `partial_front` exactly when the wire had already seen some of it.
//! - **Bounded output for a bounded schedule** — a drain loop of
//!   [`DRAIN_WORK_BOUND`] polls must reach quiescence. This is a WORK bound
//!   on a deterministic drain, not a liveness guard; the campaign's liveness
//!   guard is the wall-clock deadline in the manifest (finding F005).

#![forbid(unsafe_code)]

