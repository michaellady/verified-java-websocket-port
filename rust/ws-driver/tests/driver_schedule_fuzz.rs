/// Everything the run observed, in order. Two runs of the same schedule must
/// produce equal traces (the determinism oracle).
#[derive(Debug, Clone, PartialEq, Eq)]
struct Trace {
    dispositions: Vec<CommandDisposition>,
    events: Vec<SemanticEvent>,
    /// Bytes the modeled transport accepted, concatenated in acceptance
    /// order.
    wire: Vec<u8>,
    /// Ordered output-kind tags, so a reordering shows up as a difference.
    outputs: Vec<&'static str>,
    input_dispositions: Vec<InputDisposition>,
    terminals: usize,
    failures: usize,
    dropped: Vec<DroppedWrites>,
    refused_enqueues: usize,
    final_state: ReadyState,
    halted: bool,
}

impl Trace {
    fn empty() -> Trace {
        Trace {
            dispositions: Vec::new(),
            events: Vec::new(),
            wire: Vec::new(),
            outputs: Vec::new(),
            input_dispositions: Vec::new(),
            terminals: 0,
            failures: 0,
            dropped: Vec::new(),
            refused_enqueues: 0,
            final_state: ReadyState::Open,
            halted: false,
        }
    }
}

/// One poll result, detached from the `&mut ConnectionDriver` borrow that
/// produced it. `PollResult<'owner>` holds the driver borrowed for as long
/// as it lives, so every oracle here works on this owned copy instead.
#[derive(Debug, Clone, PartialEq, Eq)]
struct OwnedPoll {
    input: InputDisposition,
    command: Option<CommandDisposition>,
    output: OwnedOutput,
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum OwnedOutput {
    Idle,
    Write(Vec<u8>),
    Event(SemanticEvent),
    Failure,
    WritesDropped(DroppedWrites),
    Terminal,
}

impl OwnedOutput {
    fn tag(&self) -> &'static str {
        match self {
            OwnedOutput::Idle => "idle",
            OwnedOutput::Write(_) => "write",
            OwnedOutput::Event(_) => "event",
            OwnedOutput::Failure => "failure",
            OwnedOutput::WritesDropped(_) => "writes_dropped",
            OwnedOutput::Terminal => "terminal",
        }
    }
}

struct Run {
    driver: ConnectionDriver,
    sender: CommandSender,
    trace: Trace,
    /// The write the transport is currently draining. `original` is the
    /// suffix as FIRST offered for this write; `accepted` is how much of it
    /// the wire has taken since. Tracking the original rather than the
    /// re-offered tail is what lets the boundary say whether the front write
    /// is PARTLY on the wire -- the driver re-offers only the undrained
    /// tail, so a boundary that forgot the original would answer "nothing
    /// accepted" for every write it had already started.
    front: Option<FrontWrite>,
    /// What the boundary was still owed when the adapter announced it could
    /// serve the transport no longer. `DriverInput::Shutdown` abandons
    /// pending writes, so `front` is cleared at that instant and this
    /// snapshot is what the dropped-write report is checked against.
    owed_snapshot: Option<FrontWrite>,
    /// Index into `trace.outputs` where a `WritesDropped` was seen.
    dropped_at: Option<usize>,
    /// Index where a `Terminal` was seen.
    terminal_at: Option<usize>,
    halted: bool,
}

/// One transport write the boundary is draining.
#[derive(Debug, Clone, PartialEq, Eq)]
struct FrontWrite {
    /// The suffix as first offered for this write.
    original: Vec<u8>,
    /// Bytes of `original` the modeled transport has accepted.
    accepted: usize,
}

impl FrontWrite {
    fn remaining(&self) -> usize {
        self.original.len() - self.accepted
    }

    fn tail(&self) -> &[u8] {
        &self.original[self.accepted..]
    }
}

fn config() -> ConnectionConfig {
    ConnectionConfig::builder()
        .event_queue_capacity(256)
        .write_queue_capacity(256)
        .command_queue_capacity(8)
        .build()
        .expect("driver fuzz config is valid")
}

impl Run {
    fn new(role: Role, auto: AutoResponsePolicy, echo: CloseEchoPolicy) -> Run {
        let (sender, driver) = connection_driver_in_state_with_policies(
            config(),
            role,
            InitialState::Open,
            auto,
            echo,
        );
        Run {
            driver,
            sender,
            trace: Trace::empty(),
            front: None,
            owed_snapshot: None,
            dropped_at: None,
            terminal_at: None,
            halted: false,
        }
    }

    /// One owner poll, detached from the driver borrow and folded into the
    /// trace with every ordering and continuity oracle applied.
    fn poll(&mut self, label: &str, input: DriverInput<'_>) {
        if self.halted {
            return;
        }
        let is_shutdown = matches!(input, DriverInput::Shutdown);
        let owned = self.poll_owned(input);
        if is_shutdown && matches!(owned.input, InputDisposition::Consumed { .. }) {
            // The adapter has announced it can serve the transport no
            // longer, so the offered write is no longer deliverable. Snapshot
            // what was owed for the accounting oracle, then stop treating it
            // as an offer.
            self.owed_snapshot = self.front.take();
        }
        self.absorb(label, owned);
    }

    /// Detach one poll result from the `&mut ConnectionDriver` borrow.
    fn poll_owned(&mut self, input: DriverInput<'_>) -> OwnedPoll {
        let result = self.driver.poll(input);
        OwnedPoll {
            input: result.input,
            command: result.command,
            output: match result.output {
                DriverOutput::Idle => OwnedOutput::Idle,
                DriverOutput::Write(suffix) => OwnedOutput::Write(suffix.to_vec()),
                DriverOutput::Event(event) => OwnedOutput::Event(event),
                DriverOutput::Failure { .. } => OwnedOutput::Failure,
                DriverOutput::WritesDropped(report) => OwnedOutput::WritesDropped(report),
                DriverOutput::Terminal(_) => OwnedOutput::Terminal,
            },
        }
    }

    /// Fold one owned poll result into the trace.
    fn absorb(&mut self, label: &str, owned: OwnedPoll) {
        self.trace.input_dispositions.push(owned.input);
        if let Some(disposition) = owned.command {
            self.trace.dispositions.push(disposition);
        }
        self.trace.outputs.push(owned.output.tag());
        match owned.output {
            OwnedOutput::Idle => {}
            OwnedOutput::Write(suffix) => {
                match &self.front {
                    // Write-suffix continuity: once the transport has taken
                    // some of a write, every later offer of it must be
                    // exactly the undrained tail -- the driver may neither
                    // re-offer accepted bytes nor drop unaccepted ones.
                    Some(front) if front.accepted > 0 => assert_eq!(
                        suffix.as_slice(),
                        front.tail(),
                        "{label}: the driver re-offered a suffix that is not the \
                         undrained tail of the write the transport was draining"
                    ),
                    // The same untouched write, offered again.
                    Some(front) if front.original == suffix => {}
                    // A different write takes the front.
                    _ => {
                        self.front = Some(FrontWrite {
                            original: suffix,
                            accepted: 0,
                        });
                    }
                }
            }
            OwnedOutput::Event(event) => self.trace.events.push(event),
            OwnedOutput::Failure => {
                self.trace.failures += 1;
                // The modeled adapter halts at its first surfaced fatal,
                // exactly like the shipped ws-testee io_loop.
                self.halted = true;
            }
            OwnedOutput::WritesDropped(report) => {
                assert!(
                    self.dropped_at.is_none(),
                    "{label}: a second WritesDropped report was surfaced"
                );
                self.dropped_at = Some(self.trace.outputs.len() - 1);
                self.assert_shutdown_accounting(label, report);
                self.trace.dropped.push(report);
            }
            OwnedOutput::Terminal => {
                assert!(
                    self.terminal_at.is_none(),
                    "{label}: the exactly-once terminal was delivered twice"
                );
                self.terminal_at = Some(self.trace.outputs.len() - 1);
                self.trace.terminals += 1;
            }
        }
    }

    /// US-017 AC2: committed writes an ended transport can no longer deliver
    /// are handed back, never silently abandoned. The boundary knows what it
    /// was holding, so it can check the report against it.
    fn assert_shutdown_accounting(&self, label: &str, report: DroppedWrites) {
        assert_eq!(
            report.frames == 0,
            report.bytes == 0,
            "{label}: a dropped-write report with {} frames carries {} bytes",
            report.frames,
            report.bytes
        );
        match &self.owed_snapshot {
            Some(front) if front.remaining() > 0 => {
                let undrained = front.remaining();
                assert!(
                    report.frames >= 1,
                    "{label}: the transport still owed {undrained} bytes of the front \
                     write and the report accounted for no frame at all"
                );
                assert!(
                    report.bytes >= undrained,
                    "{label}: the report accounts for {} bytes but the front write \
                     alone still owed {undrained}",
                    report.bytes
                );
                assert_eq!(
                    report.partial_front,
                    front.accepted > 0,
                    "{label}: partial_front disagrees with the wire ({} bytes of the \
                     front write had already been accepted)",
                    front.accepted
                );
            }
            _ => assert!(
                !report.partial_front,
                "{label}: partial_front is set but the boundary held no partly \
                 drained front write"
            ),
        }
    }

    /// Apply one resolved schedule step.
    fn exec(&mut self, label: &str, step: &Step, kind: ProgressKind, rng: &mut SplitMix64) {
        if self.halted {
            return;
        }
        match step {
            Step::Enqueue { command, .. } => {
                // Producer purity: enqueueing must move NO protocol
                // observable. Only the owner's poll may.
                let state_before = self.driver.state();
                let counts_before = self.driver.counts();
                if self.sender.try_send(command.clone()).is_err() {
                    self.trace.refused_enqueues += 1;
                }
                assert_eq!(
                    self.driver.state(),
                    state_before,
                    "{label}: a producer enqueue moved the lifecycle state"
                );
                assert_eq!(
                    self.driver.counts(),
                    counts_before,
                    "{label}: a producer enqueue moved a protocol counter"
                );
            }
            Step::Inbound(bytes) => self.poll(label, DriverInput::Inbound(bytes)),
            Step::WriteProgress(_) => self.write_progress(label, kind, rng),
            Step::TransportEof => self.poll(label, DriverInput::TransportEof),
            Step::Shutdown => self.poll(label, DriverInput::Shutdown),
            Step::Wake => self.poll(label, DriverInput::Wake),
        }
    }

    /// Resolve a `WriteProgress` step against the suffix offered right now.
    fn write_progress(&mut self, label: &str, kind: ProgressKind, rng: &mut SplitMix64) {
        let Some(front) = self.front.clone() else {
            // No write is offered: any nonzero progress must be refused.
            let bytes = match kind {
                ProgressKind::None => 0,
                _ => 1,
            };
            self.assert_progress_refused_or_zero(label, bytes, 0);
            return;
        };
        let remaining = front.remaining();
        let bytes = match kind {
            ProgressKind::None => 0,
            ProgressKind::One => 1.min(remaining),
            ProgressKind::Partial => {
                if remaining <= 1 {
                    remaining
                } else {
                    1 + rng.below(remaining as u64 - 1) as usize
                }
            }
            ProgressKind::Whole => remaining,
            ProgressKind::Overrun => remaining + 1 + rng.below(4) as usize,
        };
        if bytes > remaining {
            self.assert_progress_refused_or_zero(label, bytes, remaining);
            return;
        }
        let owned = self.poll_owned(DriverInput::WriteProgress { bytes });
        assert_eq!(
            owned.input,
            InputDisposition::Consumed { bytes: 0 },
            "{label}: in-range write progress of {bytes}/{remaining} was not consumed"
        );
        self.trace
            .wire
            .extend_from_slice(&front.original[front.accepted..front.accepted + bytes]);
        let accepted = front.accepted + bytes;
        self.front = if accepted == front.original.len() {
            None
        } else {
            Some(FrontWrite {
                original: front.original,
                accepted,
            })
        };
        self.absorb(label, owned);
    }

    /// Progress past the offered suffix (or with nothing offered) must be
    /// refused with the exact typed error, carrying the REAL `attempted` and
    /// `remaining`, and must put no byte on the wire.
    ///
    /// It may NOT additionally be asserted here that nothing else moved. A
    /// `ConnectionDriver::poll` is an owner TURN whatever its input carries:
    /// on the same call the owner may pop a queued producer command, apply
    /// it, and commit its frame, so `state()` and `counts()` legitimately
    /// advance on a poll whose INPUT was refused. Asserting otherwise is an
    /// oracle bug, and it was one here until the campaign caught it at
    /// schedule case 283. The property in its strong form -- a refusal on a
    /// QUIESCENT owner moves literally nothing -- is where it is actually
    /// true, in
    /// `owner_driver_invalid_write_progress_on_a_quiescent_owner_moves_nothing`.
    fn assert_progress_refused_or_zero(&mut self, label: &str, bytes: usize, remaining: usize) {
        let wire_before = self.trace.wire.len();
        let owned = self.poll_owned(DriverInput::WriteProgress { bytes });
        if bytes == 0 && remaining > 0 {
            // Zero progress on an offered write is legal and inert.
            assert_eq!(owned.input, InputDisposition::Consumed { bytes: 0 });
        } else {
            assert_eq!(
                owned.input,
                InputDisposition::Rejected(DriverInputError::InvalidWriteProgress {
                    attempted: bytes,
                    remaining,
                }),
                "{label}: write progress of {bytes} against {remaining} offered bytes \
                 was not refused with the typed error"
            );
            assert_eq!(
                self.trace.wire.len(),
                wire_before,
                "{label}: a refused write progress put bytes on the wire"
            );
        }
        self.absorb(label, owned);
    }

    /// Drain to quiescence within the work bound, accepting every offered
    /// write in full.
    fn drain(&mut self, label: &str) {
        for _ in 0..DRAIN_WORK_BOUND {
            if self.halted {
                return;
            }
            let before = self.trace.outputs.len();
            self.poll(label, DriverInput::Wake);
            if let Some(front) = self.front.clone()
                && front.remaining() > 0
            {
                let owned = self.poll_owned(DriverInput::WriteProgress {
                    bytes: front.remaining(),
                });
                assert_eq!(owned.input, InputDisposition::Consumed { bytes: 0 });
                self.trace.wire.extend_from_slice(front.tail());
                self.front = None;
                self.absorb(label, owned);
                continue;
            }
            if self.trace.outputs.len() == before + 1 && self.trace.outputs[before] == "idle" {
                return;
            }
        }
        panic!(
            "{label}: the owner produced output for {DRAIN_WORK_BOUND} consecutive polls \
             on a bounded schedule without reaching quiescence"
        );
    }

    fn finish(mut self, label: &str) -> Trace {
        self.drain(label);
        if let (Some(dropped), Some(terminal)) = (self.dropped_at, self.terminal_at) {
            assert!(
                dropped < terminal,
                "{label}: the dropped-write report was surfaced AFTER the terminal; \
                 US-017 AC2 orders it before"
            );
        }
        self.trace.final_state = self.driver.state();
        self.trace.halted = self.halted;
        self.trace
    }
}

/// Execute one drawn schedule end to end.
fn execute(
    label: &str,
    schedule: &[(Step, ProgressKind)],
    role: Role,
    auto: AutoResponsePolicy,
    echo: CloseEchoPolicy,
    progress_seed: u64,
) -> Trace {
    let mut run = Run::new(role, auto, echo);
    let mut progress_rng = SplitMix64::new(progress_seed);
    for (step, kind) in schedule {
        run.exec(label, step, *kind, &mut progress_rng);
    }
    run.finish(label)
}

/// `execute` under `catch_unwind` so a driver panic fails the case with its
/// seed label (the no-panic oracle, attributably).
fn execute_checked(
    label: &str,
    schedule: &[(Step, ProgressKind)],
    role: Role,
    auto: AutoResponsePolicy,
    echo: CloseEchoPolicy,
    progress_seed: u64,
) -> Trace {
    catch_unwind(AssertUnwindSafe(|| {
        execute(label, schedule, role, auto, echo, progress_seed)
    }))
    .unwrap_or_else(|_| panic!("{label}: the owner-driver run panicked"))
}

fn draw_role(rng: &mut SplitMix64) -> Role {
    if rng.chance(2) {
        Role::Client
    } else {
        Role::Server
    }
}

fn draw_policies(rng: &mut SplitMix64) -> (AutoResponsePolicy, CloseEchoPolicy) {
    let auto = if rng.chance(2) {
        AutoResponsePolicy::PongInboundPing
    } else {
        AutoResponsePolicy::Disabled
    };
    let echo = if rng.chance(2) {
        CloseEchoPolicy::WebSocketImplComposition
    } else {
        CloseEchoPolicy::CoreDraftEcho
    };
    (auto, echo)
}

